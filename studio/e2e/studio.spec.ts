test('requires explicit approval of the fallback quote before resuming', async ({page}) => {
 await page.goto('/')
 await page.getByRole('button',{name:'Payment planner',exact:true}).click()
 await page.getByRole('button',{name:'Review & simulate payment'}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByRole('button',{name:'Approve & run simulation'}).click()
 await dialog.getByRole('button',{name:'Pause',exact:true}).click()
 await dialog.getByRole('button',{name:'Next step'}).click()
 await dialog.getByRole('button',{name:'Inject exception'}).click()
 await expect(dialog).toContainText('Fallback available. Approval required.')
 await expect(dialog).toContainText('International bank transfer')
 await expect(dialog.getByRole('button',{name:'Next step'})).toHaveCount(0)
 await dialog.getByRole('button',{name:'Approve revised quote'}).click()
 await expect(dialog).toContainText('Fallback activated safely')
 for(let i=0;i<3;i++)await dialog.getByRole('button',{name:'Next step'}).click()
 await expect(dialog).toContainText('Beneficiary usable value confirmed in the simulation.')
 await dialog.getByRole('button',{name:'View decision ledger'}).click()
 await expect(page.getByRole('table')).toContainText('Completed')
 await expect(page.getByRole('table')).toContainText('Digital-dollar bridge')
})

test('locks rerouting after commitment and records the exception', async ({page}) => {
 await page.goto('/')
 await page.getByRole('button',{name:'Payment planner',exact:true}).click()
 await page.getByRole('button',{name:'Review & simulate payment'}).click()
 const dialog=page.getByRole('dialog')
 await dialog.getByRole('button',{name:'Approve & run simulation'}).click()
 await dialog.getByRole('button',{name:'Pause',exact:true}).click()
 for(let i=0;i<2;i++)await dialog.getByRole('button',{name:'Next step'}).click()
 await expect(dialog).toContainText('Past the point of no return')
 await dialog.getByRole('button',{name:'Inject exception'}).click()
 await expect(dialog).toContainText('Investigation opened. No second payment.')
 await expect(dialog.getByRole('button',{name:'Approve revised quote'})).toHaveCount(0)
 await dialog.getByText('Event journal').click()
 await expect(dialog).toContainText('INVESTIGATION_OPENED')
 await expect(dialog).not.toContainText('FALLBACK_PROPOSED')
})

test('explains the invoice and shows why the same outage has two outcomes', async ({ page }) => {
 await page.goto('/')
 await expect(page.getByRole('heading', { name: 'Can this supplier be paid in 90 minutes?' })).toBeVisible()
 await expect(page.getByRole('complementary', { name: 'Invoice requirements' })).toContainText('US$30,000.00')
 await expect(page.getByRole('row', { name: /Digital-dollar bridge/ })).toContainText('38 min')
 await expect(page.getByRole('row', { name: /Local payout/ })).toContainText('Misses deadline')

 await page.getByRole('button', { name: 'Simulate payout outage' }).click()
 await expect(page.getByRole('heading', { name: 'Hold the payment' })).toBeVisible()
 await expect(page.getByRole('row', { name: /International bank transfer/ })).toContainText('Misses deadline')
 await expect(page.getByRole('row', { name: /Digital-dollar bridge/ })).toContainText('Partner offline')

 await page.getByRole('button', { name: 'Quote next business day' }).click()
 await expect(page.getByRole('heading', { name: 'Review a quote for next business day' })).toBeVisible()
 await expect(page.getByRole('button', { name: 'Simulate bank payment' })).toHaveCount(0)
 await page.getByRole('button', { name: 'Approve revised quote' }).click()
 await page.getByRole('button', { name: 'Simulate bank payment' }).click()
 await expect(page.getByRole('heading', { name: 'The supplier received US$30,000' })).toBeVisible()

 await page.getByRole('button', { name: 'Replay outage after commitment' }).click()
 await expect(page.getByRole('heading', { name: 'Investigate the original transfer' })).toBeVisible()
 await expect(page.getByText('Rerouting locked')).toBeVisible()
 await expect(page.getByRole('button', { name: 'Approve revised quote' })).toHaveCount(0)
 await page.getByRole('button', { name: 'Inspect decision and events' }).click()
 const record = page.getByRole('dialog', { name: 'Decision record' })
 await expect(record).toContainText('Investigation opened')
 const [file] = await Promise.all([page.waitForEvent('download'), record.getByRole('button', { name: 'Export JSON' }).click()])
 const evidence = JSON.parse(await readFile((await file.path())!, 'utf8'))
 expect(evidence.trace.intent).toMatchObject({ amount: 30000, amountMode: 'recipient', deadlineMinutes: 90 })
 expect(evidence.execution.status).toBe('investigation')
 expect(evidence.execution.events.map((event: { type: string }) => event.type)).toEqual([
  'AUTHORISED', 'FUNDS_RESERVED', 'POINT_OF_NO_RETURN', 'INVESTIGATION_OPENED',
 ])
 await record.getByRole('button', { name: 'Close dialog' }).click()
 await page.reload()
 await page.getByRole('button', { name: 'Decision ledger', exact: true }).click()
 await expect(page.getByRole('row', { name: /US\$30,000.00 to recipient.*Completed/ })).toContainText('Approved fallback: International bank transfer')
 await expect(page.getByRole('row', { name: /US\$30,000.00 to recipient.*Investigation/ })).toBeVisible()
 await page.getByRole('button', { name: 'Payment planner', exact: true }).click()
 await expect(page.getByLabel('Amount to send')).toHaveValue('25,000')
})

