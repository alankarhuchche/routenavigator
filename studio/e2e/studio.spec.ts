import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('recommends the bridge, recomputes for cost, and exports the evidence', async ({page}) => {
 const errors: string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.getByRole('button',{name:'Payment planner',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Plan a payment'})).toBeVisible()
 await expect(page.getByRole('region',{name:'Route recommendation'})).toContainText('Digital-dollar bridge')
 await page.getByRole('button',{name:'Cost',exact:true}).click()
 await page.getByRole('button',{name:'Update route recommendation'}).click()
 await expect(page.getByRole('region',{name:'Route recommendation'})).toContainText('Local payout')
 await page.getByRole('button',{name:'View decision evidence'}).click()
 const dialog=page.getByRole('dialog')
 await expect(dialog).toContainText('Local payout selected')
 const [file]=await Promise.all([page.waitForEvent('download'),dialog.getByRole('button',{name:'Export JSON'}).click()])
 const evidence=JSON.parse(await readFile((await file.path())!,'utf8'))
 expect(evidence.trace.selected).toBe('local')
 expect(evidence.trace.candidates.find((r:{id:string})=>r.id==='wallet').score).toBeNull()
 expect(errors).toEqual([])
})

